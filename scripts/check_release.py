#!/usr/bin/env python3
"""Check a source tree for private runtime files and nonportable content."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys


TEXT_EXTENSIONS = {".py", ".R", ".r", ".md", ".txt", ".json", ".toml", ".yml", ".yaml", ".lock"}
PRIVATE_EXTENSIONS = {".csv", ".tsv", ".xlsx", ".xls", ".parquet", ".npz", ".npy", ".rds", ".rdata", ".pkl", ".pickle", ".joblib", ".sqlite3", ".db"}
CJK = re.compile("[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]")
LOCAL_PATH = re.compile(r"/(?:Users|home)/[^/\s]+/|[A-Za-z]:\\Users\\")
DELIVERY_LANGUAGE = re.compile(r"(?:as an ai|generated by (?:chatgpt|codex)|the user requested|assistant response)", re.IGNORECASE)


def check(root: Path) -> dict:
    issues = []
    inspected = 0
    for path in sorted(root.rglob("*")):
        relative = path.relative_to(root)
        if ".git" in relative.parts or not path.is_file():
            continue
        inspected += 1
        suffix = path.suffix.lower()
        if path.is_symlink():
            issues.append(f"Symlink: {relative}")
        if suffix in PRIVATE_EXTENSIONS:
            issues.append(f"Runtime data or serialized analysis object: {relative}")
        if relative.parts[0] in {"data", "runs", "outputs", "validation", "reports"}:
            issues.append(f"Runtime directory contains a file: {relative}")
        generated = any(part in {"__pycache__", ".pytest_cache", ".venv", "build", "dist"}
                        or part.endswith(".egg-info") for part in relative.parts)
        if generated or suffix in {".pyc", ".log"} or path.name in {".DS_Store", ".Rhistory", ".RData", ".Rprofile"}:
            issues.append(f"Generated runtime artifact: {relative}")
        if suffix in TEXT_EXTENSIONS or path.name in {".gitignore", ".gitattributes", "LICENSE"}:
            text = path.read_text(encoding="utf-8")
            for line_number, line in enumerate(text.splitlines(), 1):
                if CJK.search(line):
                    issues.append(f"Non-English text: {relative}:{line_number}")
                if LOCAL_PATH.search(line):
                    issues.append(f"Machine-specific path: {relative}:{line_number}")
                if path.name != "check_release.py" and DELIVERY_LANGUAGE.search(line):
                    issues.append(f"Delivery-language marker: {relative}:{line_number}")
        if suffix == ".pt":
            import torch
            model = torch.load(path, map_location="cpu", weights_only=True)
            if set(model) != {"model_state_dict", "config", "input_dim"}:
                issues.append(f"Unexpected checkpoint fields: {relative}")
            elif not all(isinstance(value, torch.Tensor) for value in model["model_state_dict"].values()):
                issues.append(f"Unexpected checkpoint state value: {relative}")
    return {"files_checked": inspected, "passed": not issues, "issues": issues}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    result = check(args.root.resolve())
    print(json.dumps(result, indent=2))
    sys.exit(0 if result["passed"] else 1)


if __name__ == "__main__":
    main()
